def rec(cls=None, **kw):
    base = {
        "id": None,
        "class": None,            # apt|pip|gem|go|binary|source
        "category": None,
        "upstream": None,
        "requested_version": None,
        "resolved_version": None,
        "resolved_ref": None,
        "architectures": list(ARCH),
        "executables": [],
        "aliases": [],
        "install_location": None,
        "paths": [],
        "data_dirs": [],
        "checksum_source": None,
        "sha256": None,
        "install_method": None,
        "exposure": None,         # callable|support-only|build-only|host-only|blocked
        "banned": False,
        "requires_runtime": True,
        "probe": None,
        "version_assert": None,
        "notes": "",
    }
    base["class"] = cls
    base.update(kw)
    return base


